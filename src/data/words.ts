// Helper to shuffle cards
export function getCardsForGame(
  selectedPackIds: string[],
  maxCards: number = 80,
  customPacks: WordPack[] = []
): TabooCard[] {
  const allPacks = [...WORD_PACKS, ...customPacks];
  const activePacks = allPacks.filter((p) => selectedPackIds.includes(p.id));
  const pool = (activePacks.length > 0 ? activePacks : WORD_PACKS).flatMap((p) => p.cards);
  
  // Fisher-Yates shuffle
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, maxCards);
}
